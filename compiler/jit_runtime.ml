(* Runtime encoding of scalar Semantic IR operation records. Recipes come from
   the native emitter, with structural operand patches, never whole-region code. *)
module M = Machine_ir
let page_size = 4096
let max_operations = 32
let max_regions = 64
type recipe = { code:bytes; patches:M.operand_patch list }
let validate recipe =
  if Bytes.length recipe.code=0 || recipe.patches=[] then invalid_arg "empty JIT recipe";
  let occupied=Hashtbl.create 16 in
  List.iter(fun(p:M.operand_patch)->
    if p.at<0 || p.at+p.width>Bytes.length recipe.code ||
       (match p.operand,p.width with M.Frame id,4->id<0||id>2|M.Literal,8->false|_->true)
    then invalid_arg "invalid JIT operand relocation";
    for at=p.at to p.at+p.width-1 do
      if Hashtbl.mem occupied at then invalid_arg "overlapping JIT relocations";
      Hashtbl.add occupied at ()
    done)recipe.patches
let add_templates output recipes =
  let table=M.create()in
  let offset=ref(List.length recipes*8)in
  List.iter(fun recipe->validate recipe;M.u64 table(Int64.of_int !offset);
    offset:= !offset+8+Bytes.length recipe.code+List.length recipe.patches*8)recipes;
  List.iter(fun recipe->M.u32 table(Int64.of_int(Bytes.length recipe.code));
    M.u32 table(Int64.of_int(List.length recipe.patches));Buffer.add_bytes table.buffer recipe.code;
    List.iter(fun(p:M.operand_patch)->M.u32 table(Int64.of_int p.at);
      M.u32 table(Int64.of_int(match p.operand with M.Frame id->id|M.Literal->3)))recipe.patches)recipes;
  M.add_rodata output "__xen_jit_templates" (Buffer.contents table.buffer)
let rip output section label bytes = M.bytes output bytes;M.rip_rel32 output section label
let counter output name bytes = rip output M.Data name bytes
let emit_clock output =
  M.label output "__xen_jit_now";
  M.bytes output [0x48;0x83;0xec;0x10;0x48;0xc7;0x04;0x24;0;0;0;0;0x48;0xc7;0x44;0x24;8;0;0;0;0;0xb8;0xe4;0;0;0;0xbf;1;0;0;0;0x48;0x89;0xe6;0x0f;0x05;
